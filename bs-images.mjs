export function bsCatalogEntry(product){
 const code=String(product.code||'').normalize('NFKC').toUpperCase().trim();
 if(!code.startsWith('BS'))return null;
 const model=code.slice(2).replace(/\s/g,'').replace(/×/g,'X');
 return Object.hasOwn(BS_CATALOG_IMAGES,model)?BS_CATALOG_IMAGES[model]:null;
}
export function bsCatalogImage(product){return bsCatalogEntry(product)?.image||'';}
