export function inabaCatalogEntry(product){
 const code=String(product.code||'').normalize('NFKC').toUpperCase().trim();
 const prefix=code.match(/^(?:因幡|イナバ|イナハ|INABA)\s*/);
 if(!prefix)return null;
 const model=code.slice(prefix[0].length).replace(/\s/g,'');
 return Object.hasOwn(INABA_CATALOG_IMAGES,model)?INABA_CATALOG_IMAGES[model]:null;
}
